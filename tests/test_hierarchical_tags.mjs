import assert from 'node:assert/strict';
import { tagLabels, tagForest } from '../ailectures/static/tag-model.mjs';
import { matchesTag, matchesLecture } from '../ailectures/static/browse-model.mjs';
import { allLectureRows } from '../ailectures/static/all-lectures-model.mjs';
const one = { id:'one:a',title:'Cells',tags:['DNA'],tag_paths:[['Science','Biology','DNA'],['Science','Biology','Genetics','DNA']] };
const two = { id:'two:b',title:'Membranes',tag_paths:[['Science','Biology','Cell biology']] };
const paris = { id:'three:c',title:'A novel',tags:['Place: Paris'],tag_paths:[['Place: Europe','Place: France','Place: Paris']] };
assert.equal(matchesTag(one,'Science'),true);
assert.equal(matchesTag(one,'Sci'),false);
assert.equal(matchesTag(two,'DNA'),false);
assert.equal(matchesTag(paris,'Place: Europe'),true);
assert.equal(matchesLecture(two.id,()=>two,'Biology'),true);
assert.deepEqual(allLectureRows([one,two,paris],{tag:'Biology'}).map(row=>row.id),['one:a','two:b']);
assert.equal(tagLabels(one).filter(tag=>tag==='DNA').length,1);
const tree = tagForest([one,one,two,paris]);
const science = tree.get('Topics').get('Science');
assert.equal(science.lectures.size,2);
assert.equal(science.children.get('Biology').lectures.size,2);
assert.equal(tree.get('Places').get('Place: Europe').lectures.size,1);
assert.equal(tagForest([]).size,0);
console.log('Hierarchical tags retain specificity, exact parent matches, and unique ancestor counts.');

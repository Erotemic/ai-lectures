import assert from "node:assert/strict";
import { LearningState, mergeKnowledge, planRequest, migrateLearningState, familiarityStatus } from "../ailectures/static/learning-state.mjs";

const cache = new Map();
globalThis.localStorage = { getItem: key => cache.get(key) ?? null, setItem: (key, value) => cache.set(key, value) };
const point = (status, stamp, id) => ({ lecture_id: "math:001000", status, revision: null, updated_at: stamp, update_id: id });
const old = point("known", "2026-01-01T00:00:00Z", "old");
const newer = point("uncertain", "2026-01-02T00:00:00Z", "new");
assert.equal(mergeKnowledge({a:old}, {a:newer}).a, newer);
assert.equal(mergeKnowledge({a:newer}, {a:old}, [{lecture_id:"a"}]).a, old);
const device = new LearningState();
await device.setMany([{id:"math:001000",status:"uncertain"}]);
assert.equal((await new LearningState().load())["math:001000"].status,"uncertain");
let online = false, calls = 0;
const service = {api:async()=>({knowledge:{}}),post:async(path,event)=>{
  calls++;
  if(!online) throw Error("offline");
  return {...event,update_id:event.id,updated_at:"2026-01-03T00:00:00Z"};
}};
const named = new LearningState("listener",service);
await named.setMany([{id:"math:001000",status:"known"}]);
assert.equal(named.records["math:001000"].status,"known");
assert.equal(JSON.parse(cache.get('ailectures:knowledge-pending:listener')).length,1);
online = true;
await named.load();
assert.equal(JSON.parse(cache.get('ailectures:knowledge-pending:listener')).length,0);
assert.equal(named.records["math:001000"].status,"known");
assert.equal(new LearningState("other").records["math:001000"],undefined);
cache.set('ailectures:knowledge:alias',JSON.stringify({'math:001000':old}));
cache.set('ailectures:knowledge-pending:alias',JSON.stringify([{id:'old',lecture_id:'math:001000',status:'known',revision:null}]));
cache.set('ailectures:knowledge:canonical',JSON.stringify({'math:001000':newer}));
cache.set('ailectures:knowledge-pending:canonical',JSON.stringify([{id:'new',lecture_id:'math:001000',status:'uncertain',revision:null}]));
migrateLearningState('alias','canonical');
assert.equal(new LearningState('canonical').records['math:001000'].status,'uncertain');
assert.deepEqual(JSON.parse(cache.get('ailectures:knowledge-pending:canonical')).map(row=>row.id),['old','new']);
assert.deepEqual(JSON.parse(cache.get('ailectures:knowledge-pending:alias')),[]);
// A second choice made while the first save returns must not be rolled back.
let finish;
const delayed = new LearningState("delayed",{post:async(path,event)=>new Promise(resolve=>{
  if (!finish) finish=()=>resolve({...event,update_id:event.id,updated_at:"2026-01-04T00:00:00Z"});
  else resolve({...event,update_id:event.id,updated_at:"2026-01-05T00:00:00Z"});
})});
const saving=delayed.setMany([{id:"math:001000",status:"known"}]);
const changing=delayed.setMany([{id:"math:001000",status:"unknown"}]);
finish();await Promise.all([saving,changing]);
assert.equal(delayed.records["math:001000"].status,"unknown");
const graph={nodes:{'math:001000':{id:'math:001000',kind:'lecture',categories:['Mathematics']},'math:002000':{id:'math:002000',kind:'lecture',categories:['Mathematics']}},collections:[{id:'math:main',lectures:['math:001000','math:002000']}]};
const request=planRequest(graph,{mode:'collection',collection:'math:main',start:'math:002000'},{'math:001000':old,'math:002000':newer});
assert.deepEqual(request.goals,['math:002000']);
assert.deepEqual(request.known,['math:001000']);
assert.deepEqual(request.uncertain,['math:002000']);
assert.equal(request.assume_uncertain,false);
assert.deepEqual(planRequest(graph,{mode:'ready',category:'Mathematics'},{}).scope,['math:001000','math:002000']);
assert.equal(planRequest(graph,{mode:'goal',goal:'math:002000',start:'math:001000'},{}).start,null);
const expanded={...graph,nodes:{...graph.nodes,'math:001000':{...graph.nodes['math:001000'],revision:'metadata-new',knowledge_revision:'expanded-content'}}};
const formerPart={...old,revision:'original-short-part'};
assert.equal(familiarityStatus(formerPart,expanded.nodes['math:001000']),'uncertain');
assert.deepEqual(planRequest(expanded,{mode:'goal',goal:'math:002000'},{'math:001000':formerPart}).known,[]);
assert.deepEqual(planRequest(expanded,{mode:'goal',goal:'math:002000'},{'math:001000':formerPart}).uncertain,['math:001000']);
assert.equal(familiarityStatus({...formerPart,revision:'expanded-content'},expanded.nodes['math:001000']),'known');
console.log('Learning background persists independently of playback, survives failed saves, and preserves uncertainty and listener isolation');
